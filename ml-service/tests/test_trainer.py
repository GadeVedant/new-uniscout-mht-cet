def test_trainer_dry_run_returns_metrics() -> None:
    """Trainer.train with dry_run=True returns a metrics dict without writing files."""
    import tempfile, os
    df = _make_fe_df([2021, 2022, 2023], n_per_year=20)
    trainer = Trainer()
    with tempfile.TemporaryDirectory() as tmp:
        result = trainer.train(df, tmp, dry_run=True)

    assert "validation_mae" in result
    assert "validation_within_1_accuracy" in result
    assert "validation_directional_accuracy" in result
    assert "calibration_coverage" in result
    assert "metrics_by_category" in result
    assert "metrics_by_cap_round" in result
    assert "metrics_by_branch" in result


def test_trainer_requires_at_least_two_years() -> None:
    """Trainer.train raises ValueError when only one year is present."""
    df = _make_fe_df([2022], n_per_year=20)
    trainer = Trainer()
    with pytest.raises(ValueError, match="at least 2 distinct years"):
        trainer.train(df, "/tmp/unused", dry_run=True)


def test_trainer_missing_feature_column_raises() -> None:
    """Trainer.train raises ValueError when a required feature column is missing."""
    df = _make_fe_df([2021, 2022], n_per_year=20)
    df = df.drop(columns=["cutoff_t1"])
    trainer = Trainer()
    with pytest.raises(ValueError, match="missing required columns"):
        trainer.train(df, "/tmp/unused", dry_run=True)


def test_build_folds_no_leakage_simple() -> None:
    """build_folds: training rows always have year < validation year."""
    df = _make_fe_df([2020, 2021, 2022], n_per_year=15)
    trainer = Trainer()
    folds = trainer.build_folds(df)
    assert len(folds) >= 1
    for df_train, df_val in folds:
        val_year = df_val["year"].unique()[0]
        assert (df_train["year"] < val_year).all()


def test_blend_p50_scalar() -> None:
    """_blend_p50 scalar check: 0.70*80 + 0.30*60 == 74.0."""
    result = _blend_p50(np.array([80.0]), np.array([60.0]))
    assert abs(result[0] - 74.0) < 1e-9
